// SHINE Master Specification — combined-doc generator
// Reads spec/parts/NN-*.md in order and writes spec/SHINE-MASTER-SPEC-v1.0.md.
// Usage: bun spec/build.js
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const partsDir = join(here, "parts");
const outFile = join(here, "SHINE-MASTER-SPEC-v1.0.md");

const files = readdirSync(partsDir)
  .filter((f) => f.endsWith(".md"))
  .sort();

if (files.length === 0) {
  console.error("No part files found in spec/parts/");
  process.exit(1);
}

const parts = files.map((f) => ({
  name: f,
  content: readFileSync(join(partsDir, f), "utf8").trim(),
}));

// Build a table of contents from the first H1 of each part.
const toc = parts
  .map(({ name, content }) => {
    const title = content.match(/^# (.+)$/m)?.[1] ?? name.replace(".md", "");
    const anchor = title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");
    return `- [${title}](#${anchor})`;
  })
  .join("\n");

const header = [
  "# SHINE Enterprise Master Specification v1.0",
  "",
  "> **Generated document.** Source of truth: `spec/parts/`. Rebuild with",
  "> `bun spec/build.js`. Do not edit this file directly.",
  "",
  "---",
  "",
  "## Table of Contents",
  "",
  toc,
  "",
].join("\n");

const body = parts.map((p) => p.content).join("\n\n---\n\n");

writeFileSync(outFile, header + "\n\n---\n\n" + body + "\n");
console.log(
  `Combined spec written: ${outFile}\nParts included: ${parts.length} (${files[0]} … ${files[files.length - 1]})`,
);
