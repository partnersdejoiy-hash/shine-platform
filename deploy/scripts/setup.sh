#!/usr/bin/env bash
# =============================================================================
# SHINE self-hosted provisioning script (Powered by DEJOIY)
#
#  1. Generates every secret (or reuses existing .env values)
#  2. Writes .env next to docker-compose.yml
#  3. Boots the full stack: postgres redis minio meilisearch livekit egress
#     coturn novu prometheus grafana loki promtail nginx api
#  4. Runs Prisma migrations + seed (DEJOIY org + super admin)
#  5. Prints the URLs + what to configure
#
# Usage:  bash deploy/scripts/setup.sh
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="$ROOT/.env"

gen() { openssl rand -hex "${1:-32}"; }

echo "==> SHINE self-hosted setup"

# ---------- Load or create .env --------------------------------------------
if [[ -f "$ENV_FILE" ]]; then
  echo "    .env exists — reusing existing secrets."
  # shellcheck disable=SC1090
  source "$ENV_FILE"
else
  echo "    Generating secrets and writing $ENV_FILE"
  cat > "$ENV_FILE" <<'EOF'
# SHINE self-hosted environment — generated by deploy/scripts/setup.sh
PUBLIC_SITE_URL=https://shine.dejoiy.com
# Convex deployment used by the frontend + backend (see .env.example).
# Required to build the web container — e.g. https://my-project-my-team.convex.cloud
CONVEX_URL=
JWT_SECRET=__JWT__
SUPER_ADMIN_EMAIL=deepak.sharma@dejoiy.com
SUPER_ADMIN_PASSWORD=__SUPERADMIN__
POSTGRES_USER=shine
POSTGRES_PASSWORD=__PG__
POSTGRES_DB=shine
REDIS_PASSWORD=__REDIS__
MINIO_ROOT_USER=shine-admin
MINIO_ROOT_PASSWORD=__MINIO__
MINIO_BUCKET=shine
MINIO_PUBLIC_URL=${PUBLIC_SITE_URL}/minio
MEILI_MASTER_KEY=__MEILI__
LIVEKIT_API_KEY=shine-livekit
LIVEKIT_API_SECRET=__LIVEKIT__
LIVEKIT_URL=ws://livekit:7880
PUBLIC_LIVEKIT_URL=wss://livekit.example.com
LIVEKIT_EGRESS_URL=http://livekit-egress:7882
TURN_REALM=shine.dejoiy.com
TURN_STATIC_AUTH_SECRET=__TURN__
# WebRTC TURN relay credentials (keep in sync with deploy/coturn/turnserver.conf)
TURN_URL=turn:shine.dejoiy.com:3478?transport=udp
TURN_USERNAME=dejoiy-turn
TURN_PASSWORD=__TURN_PASS__
RTC_STUN_URLS=stun:stun.l.google.com:19302,stun:stun1.l.google.com:19302
NOVU_SECRET=__NOVU__
NOVU_FROM=notifications@shine.dejoiy.com
NOVU_API_KEY=
SMTP_HOST=smtp.resend.com
SMTP_PORT=465
SMTP_USER=resend
SMTP_PASS=__RESEND__
SMTP_SECURE=true
SMTP_FROM=welcome@dejoiy.com
AUTH_GOOGLE_ID=
AUTH_GOOGLE_SECRET=
AUTH_MICROSOFT_ENTRA_ID_ID=
AUTH_MICROSOFT_ENTRA_ID_SECRET=
AUTH_GITHUB_ID=
AUTH_GITHUB_SECRET=
AUTH_APPLE_ID=
AUTH_APPLE_SECRET=
# Razorpay billing (see https://dashboard.razorpay.com -> API Keys)
# RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET are required for payments;
# RAZORPAY_WEBHOOK_SECRET is required for webhook verification.
RAZORPAY_KEY_ID=
RAZORPAY_KEY_SECRET=
RAZORPAY_WEBHOOK_SECRET=__RZ_WEBHOOK__
GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=__GRAFANA__
# ---- Profile-gated self-hosted services (start with --profile <name>) ----
ACME_EMAIL=admin@dejoiy.com
TRAEFIK_DASHBOARD_HOST=traefik.shine.dejoiy.com
WIKI_JWT_SECRET=__WIKI__
ONLYOFFICE_JWT_SECRET=__OFFICE__
GLITCHTIP_SECRET_KEY=__GLITCH__
POSTHOG_SECRET_KEY=__POSTHOG__
CLICKHOUSE_PASSWORD=__CLICK__
N8N_ENCRYPTION_KEY=__N8N__
RESTIC_PASSWORD=__RESTIC__
RABBITMQ_PASSWORD=__RABBIT__
INFISICAL_ENCRYPTION_KEY=__INFISICAL__
INFISICAL_AUTH_SECRET=__INFISICAL_AUTH__
TIMEZONE=Asia/Kolkata
EOF
  # Substitute generated secrets (preserving the heredoc above)
  sed -i "s|__JWT__|$(gen 32)|; s|__SUPERADMIN__|$(gen 16)|; s|__PG__|$(gen 16)|; s|__REDIS__|$(gen 16)|; s|__MINIO__|$(gen 24)|; s|__MEILI__|$(gen 32)|; s|__LIVEKIT__|$(gen 32)|; s|__TURN__|$(gen 32)|; s|__TURN_PASS__|$(gen 16)|; s|__NOVU__|$(gen 32)|; s|__RZ_WEBHOOK__|$(gen 32)|; s|__GRAFANA__|$(gen 16)|; s|__RESEND__||; s|__WIKI__|$(gen 32)|; s|__OFFICE__|$(gen 32)|; s|__GLITCH__|$(gen 32)|; s|__POSTHOG__|$(gen 32)|; s|__CLICK__|$(gen 24)|; s|__N8N__|$(gen 32)|; s|__RESTIC__|$(gen 32)|; s|__RABBIT__|$(gen 16)|; s|__INFISICAL__|$(gen 32)|; s|__INFISICAL_AUTH__|$(gen 32)|" "$ENV_FILE"
  echo "    Done. Edit PUBLIC_SITE_URL / SMTP_* / TURN_REALM before continuing."
fi

# ---------- Environment checks ---------------------------------------------
command -v docker >/dev/null 2>&1 || { echo "ERROR: docker is required."; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "ERROR: docker compose v2 is required."; exit 1; }

# ---------- Boot ------------------------------------------------------------
echo "==> Building images (first run may take a few minutes)"
docker compose -f "$ROOT/docker-compose.yml" build api

echo "==> Starting infrastructure"
docker compose -f "$ROOT/docker-compose.yml" up -d postgres redis minio minio-init meilisearch livekit livekit-egress coturn novu novu-mongo prometheus grafana loki promtail nginx api

echo "==> Waiting for healthy services"
docker compose -f "$ROOT/docker-compose.yml" exec -T api sh -c \
  'until wget -qO- http://localhost:3001/health >/dev/null 2>&1; do echo "  waiting for api..."; sleep 3; done'
echo "    API is healthy."

# ---- Frontend (Vite SPA on nginx, served on 127.0.0.1:8090) ----------------
# This is the container that Caddy reverse-proxies app.shine.dejoiy.com (and
# meet.dejoiy.com) to. Without it the site returns 502 Bad Gateway.
if [[ -z "${CONVEX_URL:-}" ]]; then
  echo "ERROR: CONVEX_URL is required (your Convex deployment, e.g."
  echo "       https://my-project-my-team.convex.cloud). Add it to $ENV_FILE"
  echo "       before building the frontend."
  exit 1
fi

# ---------- Build & start the frontend ---------------------------------------
echo "==> Building the frontend (Vite SPA) — first build takes a few minutes"
docker compose -f "$ROOT/docker-compose.yml" build web
docker compose -f "$ROOT/docker-compose.yml" up -d web

echo "==> Waiting for the frontend to answer on 127.0.0.1:8090"
for i in {1..30}; do
  if curl -fsS http://127.0.0.1:8090/ >/dev/null 2>&1; then
    echo "    Frontend is up."
    break
  fi
  echo "    waiting for web... ($i)"
  sleep 2
done

# ---------- Report -----------------------------------------------------------
PUBLIC=$(grep '^PUBLIC_SITE_URL=' "$ENV_FILE" | cut -d= -f2)
echo ""
echo "=============================================================================="
echo " SHINE is coming up. Summary:"
echo "   App ............ ${PUBLIC}"
echo "   API ............ ${PUBLIC}/api  (health: ${PUBLIC}/api/health)"
echo "   MinIO console .. http://<server>:9001"
echo "   Grafana ........ http://<server>:3001"
echo "   Novu ........... ${PUBLIC}/notifications"
echo "   Super admin .... deepak.sharma@dejoiy.com"
echo ""
echo " Remaining steps:"
echo "   1. Edit $ENV_FILE: SMTP_HOST/USER/PASS (all emails go through YOUR SMTP)"
echo "   2. Point DNS shine.dejoiy.com -> this server; add TLS certs to deploy/nginx/certs"
echo "   3. Open UDP 3478/3479/5349 + 50000-50100 for LiveKit/Coturn"
echo "   4. Copy TURN_URL / TURN_USERNAME / TURN_PASSWORD from $ENV_FILE into the app's Keys tab"
echo "   5. Set CONVEX_URL in $ENV_FILE, then run:  docker compose build web && docker compose up -d web"
echo ""
echo " Optional profile-gated services (see docker-compose.yml header):"
echo "   docker compose --profile knowledge up -d   # Wiki.js"
echo "   docker compose --profile office up -d      # OnlyOffice Docs"
echo "   docker compose --profile ops up -d         # Uptime Kuma + exporters + GlitchTip"
echo "   docker compose --profile analytics up -d   # PostHog"
echo "   docker compose --profile workflow up -d    # n8n"
echo "   docker compose --profile media up -d       # Tika + Gotenberg + ClamAV"
echo "   docker compose --profile security up -d    # CrowdSec"
echo "   docker compose --profile backup up -d      # Restic backups"
echo "   docker compose --profile future up -d      # RabbitMQ + Infisical + Flagsmith"
echo "=============================================================================="
