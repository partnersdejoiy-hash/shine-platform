export function searchEmojis(q: string): string[] {
  const query = q.toLowerCase().trim();
  if (!query) return [];
  const out: string[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const e of cat.emojis) {
      if (e.toLowerCase().includes(query)) out.push(e);
    }
  }
  return out.slice(0, 40);
}

